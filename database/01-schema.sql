SET NAMES utf8mb4;
CREATE TABLE tblThanhVien (
 id INT PRIMARY KEY AUTO_INCREMENT, tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
 matKhau VARCHAR(255) NOT NULL, hoTen VARCHAR(100) NOT NULL, vaiTro VARCHAR(20) NOT NULL
);
CREATE TABLE tblPhim (
 id INT PRIMARY KEY AUTO_INCREMENT, tenPhim VARCHAR(255) NOT NULL UNIQUE,
 theLoai VARCHAR(100) NOT NULL, thoiLuong INT NOT NULL CHECK(thoiLuong>0), moTa TEXT
);
CREATE TABLE tblSuatChieu (
 id INT PRIMARY KEY AUTO_INCREMENT, idPhim INT NOT NULL, ngayGioChieu DATETIME NOT NULL,
 phongChieu VARCHAR(20) NOT NULL, giaVe DECIMAL(12,0) NOT NULL CHECK(giaVe>=0),
 FOREIGN KEY(idPhim) REFERENCES tblPhim(id)
);
CREATE TABLE tblVeMua (
 id INT PRIMARY KEY AUTO_INCREMENT, idThanhVien INT NOT NULL, idSuatChieu INT NOT NULL,
 ngayMua DATETIME NOT NULL, INDEX(ngayMua), UNIQUE(id,idSuatChieu),
 FOREIGN KEY(idThanhVien) REFERENCES tblThanhVien(id), FOREIGN KEY(idSuatChieu) REFERENCES tblSuatChieu(id)
);
CREATE TABLE tblGheVeMua (
 id INT PRIMARY KEY AUTO_INCREMENT, idVeMua INT NOT NULL, idSuatChieu INT NOT NULL,
 soGhe VARCHAR(5) NOT NULL, UNIQUE(idSuatChieu,soGhe),
 FOREIGN KEY(idVeMua,idSuatChieu) REFERENCES tblVeMua(id,idSuatChieu)
);
